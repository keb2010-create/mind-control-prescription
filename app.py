import time

# 1. 마인드 컨트롤 처방을 결정하는 함수 (함수 & 조건문 활용)
def get_prescription(problem_num, stress_level):
    print("\n" + "="*40)
    print("💊 [심리적 문제 마인드 컨트롤 간단 처방전]")
    print("="*40)
    
    # 키워드 1: 학업 및 진로 스트레스
    if problem_num == 1:
        print("▶ 선택 고민: 학업 및 진로 스트레스")
        if stress_level <= 2:
            print("💡 처방: 가벼운 긴장 상태네요! 10분간 눈을 감고 명상을 하거나 좋아하는 음악을 들어보세요.")
        elif stress_level <= 4:
            print("💡 처방: 머리를 식힐 시간이 필요해요. 스마트폰을 끄고 동네 한 바퀴 산책을 다녀오거나 맛있는 간식을 먹어보세요.")
        else:
            print("💡 처방: 번아웃 직전입니다! 오늘 하루는 책상에서 완전히 벗어나 푹 잠을 자거나 보고 싶었던 OTT 정주행을 추천합니다.")

    # 키워드 2: 친구 관계 문제
    elif problem_num == 2:
        print("▶ 선택 고민: 친구 관계 문제")
        if stress_level <= 2:
            print("💡 처방: 사소한 오해일 수 있어요. 혼자 차분히 생각할 시간을 가지며 명상을 해보세요.")
        elif stress_level <= 4:
            print("💡 처방: 기분 전환이 필요해요. 영화를 보며 다른 세상에 몰입하거나 맛있는 음식을 먹으며 스트레스를 날려보세요.")
        else:
            print("💡 처방: 마음이 많이 지쳤군요. 나를 온전히 이해해 주는 다른 편한 친구와 수다를 떨거나, 훌쩍 근교로 여행(드라이브)을 떠나보세요.")

    # 키워드 3: 가족 관계 문제
    elif problem_num == 3:
        print("▶ 선택 고민: 가족 관계 문제")
        if stress_level <= 2:
            print("💡 처방: 잠시 각자의 시간이 필요해요. 방에서 조용히 좋아하는 OTT 콘텐츠를 보며 기분을 환기해 보세요.")
        elif stress_level <= 4:
            print("💡 처방: 집 밖으로 잠시 나가보세요. 바깥 공기를 마시며 산책을 하거나 카페에서 맛있는 음료를 마시는 걸 추천합니다.")
        else:
            print("💡 처방: 감정이 많이 격해진 상태예요. 밖으로 나가 드라이브를 하거나 영화를 보며 감정을 가라앉힌 뒤, 일찍 잠자리에 들어보세요.")

    # 키워드 4: 이유 없는 무기력증 및 우울감
    elif problem_num == 4:
        print("▶ 선택 고민: 이유 없는 무기력증 및 우울감")
        if stress_level <= 2:
            print("💡 처방: 작은 성취감이 필요해요. 가볍게 방 정리를 하거나 5분만 스트레칭과 명상을 해보세요.")
        elif stress_level <= 4:
            print("💡 처방: 오감을 자극해 보세요! 평소 먹고 싶었던 아주 맛있는 음식을 먹거나, 친한 친구와 신나게 수다를 떨어보세요.")
        else:
            print("💡 처방: 에너지가 완전히 방전되었어요. 아무 생각 없이 푹 잠을 자거나, 주말을 이용해 낯선 곳으로 여행을 다녀오는 것을 추천합니다.")
    
    print("="*40 + "\n")


# 2. 메인 프로그램 실행 함수 (반복문 활용)
def main():
    print("🌟 심리적 문제 마인드 컨트롤 간단 처방 프로그램에 오신 것을 환영합니다! 🌟")
    
    # 사용자가 종료(0번)를 선택할 때까지 무한 반복
    while True:
        print("\n[현재 겪고 있는 심리적 문제 키워드 목록]")
        print("1. 학업 및 진로 스트레스")
        print("2. 친구 관계 문제")
        print("3. 가족 관계 문제")
        print("4. 이유 없는 무기력증 및 우울감")
        print("0. 프로그램 종료")
        
        # 키워드 선택 입력받기
        choice = input("\n👉 해당하는 문제의 번호를 선택하세요 (0~4): ")
        
        # 0번 입력 시 반복문 탈출(종료)
        if choice == '0':
            print("\n마음이 한결 편안해지셨길 바랍니다. 프로그램을 종료합니다. 안녕히 가세요! 👋")
            break
        
        # 1~4번 외의 잘못된 값을 입력했을 때 예외 처리
        if choice not in ['1', '2', '3', '4']:
            print("⚠️ 잘못된 입력입니다. 0부터 4 사이의 숫자만 입력해 주세요.")
            continue
            
        problem_num = int(choice)
        
        # 스트레스 지수 입력받기 (올바른 값이 들어올 때까지 반복)
        while True:
            stress_input = input("👉 현재 느끼는 스트레스 지수를 1부터 5까지 숫자로 입력하세요 (1: 매우 낮음 ~ 5: 매우 높음): ")
            if stress_input in ['1', '2', '3', '4', '5']:
                stress_level = int(stress_input)
                break
            else:
                print("⚠️ 1부터 5 사이의 숫자만 입력해 주세요.")
        
        print("\n처방전을 분석 중입니다...")
        time.sleep(1) # 1초 대기 효과로 프로그램 느낌 살리기
        
        # 처방 함수 호출
        get_prescription(problem_num, stress_level)
        
        # 계속 진행할지 물어보기
        again = input("다른 고민도 처방받으시겠습니까? (y/n): ")
        if again.lower() != 'y':
            print("\n오늘도 당신의 마음을 응원합니다! 프로그램을 종료합니다. 😊")
            break

# 프로그램 시작점
if __name__ == "__main__":
    main()
